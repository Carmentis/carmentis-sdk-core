import { TagHandler } from "./TagHandler";
import { CertificateTagHandler } from "./CertificateTagHandler";
import { DigestDataTagHandler } from "./DigestDataTagHandler";
import { LinkTagHandler } from "./LinkTagHandler";
import { RepresentationTagHandler } from "./RepresentationTagHandler";
import { SignatureTagHandler } from "./SignatureTagHandler";
import { VcVpTagHandler } from "./VcVpTagHandler";
import { ResolutionNode } from '../type/valibot/resolutionNodes/ResolutionNodes';
import { ResolverPath } from '../resolver/ResolverPath';
import { Provider } from '../providers/Provider';
import {
    ResolverInput,
    ResolverOutput,
    ResolverHydrator,
    TagHandlerOutput,
} from '../resolver/ResolverTypes';

export class TagProcessor {
    private registeredTags = new Map<string, { handler: TagHandler, noOutput: boolean }>();
    private nodes = new Map<string, ResolutionNode[]>;

    constructor(
        protected readonly hydrator: ResolverHydrator,
        protected readonly provider: Provider,
        protected readonly input: ResolverInput | ResolverOutput,
    ) {
        this.register(CertificateTagHandler);
        this.register(DigestDataTagHandler);
        this.register(LinkTagHandler);
        this.register(RepresentationTagHandler);
        this.register(SignatureTagHandler);
        this.register(VcVpTagHandler);
    }

    register(handlerClass: new (hydrator: ResolverHydrator, provider: Provider, input: ResolverInput | ResolverOutput) => TagHandler): void {
        const handler = new handlerClass(this.hydrator, this.provider, this.input);
        const tags = handler.getTags();
        for (const tag of tags) {
            this.registeredTags.set(tag.name, { handler, noOutput: tag.noOutput ?? false });
        }
    }

    getRegisteredTag(tag: string) {
        return this.registeredTags.get(tag);
    }

    clearNodes() {
        this.nodes.clear();
    }

    getNodes() {
        return this.nodes;
    }

    async process(tag: string, object: any, path: ResolverPath): Promise<TagHandlerOutput> {
        const tagEntry = this.registeredTags.get(tag);

        if (tagEntry === undefined) {
            throw new Error(`Unknown tag: '${tag}'`);
        }

        try {
            const res = await tagEntry.handler.handle(tag, object, path);
            if (tagEntry.noOutput && res.output !== undefined) {
                throw new Error(`internal error: some output was generated by a tag '${tag}' which is flagged with 'noOutput'`);
            }
            this.mapNode(res, ResolverPath.clone(path).removeLast());
            return res;
        }
        catch {
            return { node: null, resolveOutput: false };
        }
    }

    mapNode(tagOutput: TagHandlerOutput, path: ResolverPath) {
        if (tagOutput.node === null) {
            return;
        }
        const output = tagOutput.output;
        if (output !== undefined && output !== null && !Array.isArray(output) && typeof output === 'object') {
            for (const key of Object.keys(output)) {
                const newPath = ResolverPath.clone(path).append(key);
                const serializedPath = newPath.serialize();
                let entry = this.nodes.get(serializedPath);
                if (entry === undefined) {
                    entry = [];
                    this.nodes.set(serializedPath, entry);
                }
                entry.push(tagOutput.node);
            }
        }
    }
}
